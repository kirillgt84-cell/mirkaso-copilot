"""A ``DataProvider`` backed by the synthetic JSON files in ``mirkaso_copilot/fixtures``.

Used by the demo so the agent can run against the real Meta Model API without access to
the private Mirkaso product. The data is synthetic demo data generated by
``scripts/generate_fixtures.py``; every timestamp in it is fixed relative to ``BASE_TIME``.

By default every timestamp is shifted by ``now - BASE_TIME`` when the provider is created,
so the data looks current while the gaps between timestamps stay exactly as stored.
``fixed_time=True`` keeps the stored timestamps, for tests and evaluations.

Filters and limits behave the way the tools expect from a real provider: scanner signals
are filtered by every argument and returned strongest first, an unknown symbol returns
``None`` (the tool turns that into ``not_found``), and history covers the requested window
up to what the fixtures hold (7 days of macro history, 48 hours of open interest).
"""

import json
from datetime import datetime, timedelta
from functools import cache
from importlib import resources
from typing import Any

from mirkaso_copilot.envelope import to_utc_iso, utc_now
from mirkaso_copilot.tools._common import parse_ts

FIXTURE_PACKAGE = "mirkaso_copilot.fixtures"
SYNTHETIC_NOTICE = "synthetic demo data - not real market data"
QUOTE_SUFFIX = "USDT"
# Keys whose values are timestamps. ``base_time`` is metadata and is never shifted.
TIMESTAMP_KEYS = frozenset({"as_of", "ts", "detected_at"})


@cache
def load_fixture(name: str) -> dict[str, Any]:
    text = resources.files(FIXTURE_PACKAGE).joinpath(f"{name}.json").read_text("utf-8")
    payload = json.loads(text)
    if payload.get("notice") != SYNTHETIC_NOTICE:
        raise ValueError(f"fixture {name} is not marked as synthetic demo data")
    return payload


BASE_TIME: str = load_fixture("scanner")["base_time"]


def shift_timestamps(value: Any, offset: timedelta) -> Any:
    """Deep copy of ``value`` with every timestamp under ``TIMESTAMP_KEYS`` moved by ``offset``."""
    if isinstance(value, dict):
        return {
            k: to_utc_iso(parse_ts(v) + offset)
            if k in TIMESTAMP_KEYS and isinstance(v, str)
            else shift_timestamps(v, offset)
            for k, v in value.items()
        }
    if isinstance(value, list):
        return [shift_timestamps(v, offset) for v in value]
    return value


def _pair(symbol: str) -> str:
    symbol = symbol.upper()
    return symbol if symbol.endswith(QUOTE_SUFFIX) else symbol + QUOTE_SUFFIX


def _copy(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return [dict(r) for r in rows]


class FixtureProvider:
    """Serves the bundled synthetic fixtures. Returned rows are copies, safe to mutate.

    ``now`` (default: the current UTC time) sets the shift target; it is ignored when
    ``fixed_time`` is true. The offset is truncated to whole seconds.
    """

    def __init__(self, *, fixed_time: bool = False, now: datetime | None = None) -> None:
        if fixed_time:
            self.offset = timedelta(0)
        else:
            delta = (now or utc_now()) - parse_ts(BASE_TIME)
            self.offset = timedelta(seconds=int(delta.total_seconds()))
        self._fixtures: dict[str, dict[str, Any]] = {}

    @property
    def base_time(self) -> str:
        """``BASE_TIME`` after the shift: the ``as_of`` of every result."""
        return to_utc_iso(parse_ts(BASE_TIME) + self.offset)

    def _fixture(self, name: str) -> dict[str, Any]:
        if name not in self._fixtures:
            raw = load_fixture(name)
            self._fixtures[name] = shift_timestamps(raw, self.offset) if self.offset else raw
        return self._fixtures[name]

    async def scanner_signals(
        self,
        *,
        min_score: int,
        direction: str | None,
        confidence: str | None,
        base_asset: str | None,
        limit: int,
    ) -> dict[str, Any]:
        fixture = self._fixture("scanner")
        rows = [
            s
            for s in fixture["signals"]
            if s["score"] >= min_score
            and (direction is None or s["direction"] == direction)
            and (confidence is None or s["confidence"] == confidence)
            and (base_asset is None or s["base_asset"] == base_asset.upper())
        ]
        rows.sort(key=lambda s: s["score"], reverse=True)
        return {"as_of": fixture["as_of"], "signals": _copy(rows[:limit])}

    async def sector_indices(self, *, asset_class: str | None) -> dict[str, Any]:
        fixture = self._fixture("sectors")
        rows = [s for s in fixture["sectors"] if asset_class in (None, s["asset_class"])]
        return {"as_of": fixture["as_of"], "sectors": _copy(rows)}

    async def macro_regime(self) -> dict[str, Any]:
        fixture = self._fixture("macro")
        return {"as_of": fixture["as_of"], **fixture["current"]}

    async def macro_regime_history(self, *, days: int) -> dict[str, Any]:
        fixture = self._fixture("macro")
        start = parse_ts(fixture["as_of"]) - timedelta(days=days)
        return {"points": _copy([p for p in fixture["history"] if parse_ts(p["ts"]) > start])}

    async def coin_derivatives(self, *, symbol: str) -> dict[str, Any] | None:
        fixture = self._fixture("derivatives")
        row = fixture["coins"].get(_pair(symbol))
        return None if row is None else {"as_of": fixture["as_of"], **row}

    async def coin_open_interest_history(self, *, symbol: str) -> dict[str, Any]:
        points = self._fixture("derivatives")["open_interest_history"].get(_pair(symbol), [])
        return {"points": _copy(points)}
